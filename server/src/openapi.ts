export function openApiDocument() {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const [method, path, tag, summary, auth, body] of OPS) {
    const params = [...path.matchAll(/\{(\w+)\}/g)].map((m) => ({ name: m[1], in: 'path', required: true, schema: { type: 'string' } }));
    paths[path] ??= {};
    paths[path][method] = {
      tags: [tag],
      summary,
      description: `Access: ${auth}.${body ? ` Body validated by \`${body}\` (shared/src/schemas.ts).` : ''}`,
      ...(params.length ? { parameters: params } : {}),
      ...(body ? { requestBody: { required: true, content: { 'application/json': { schema: { type: 'object', description: body } } } } } : {}),
      ...(['session', 'patient+premium', 'caretaker-link', 'pharmacy', 'admin', 'reviewer', 'demo-only'].includes(auth) ? { security: [{ session: [] }] } : {}),
      responses: {
        '200': { description: 'OK' },
        default: { description: 'Error', content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } } },
      },
    };
  }
  return {
    openapi: '3.1.0',
    info: {
      title: 'MEDIMATE API',
      version: '0.1.0',
      description: 'Track • Remind • Live Healthier. Simulated SMS/USSD and demo payments are clearly labelled; see docs/.',
    },
    components: {
      securitySchemes: { session: { type: 'apiKey', in: 'cookie', name: 'mm_session' } },
      schemas: {
        Error: {
          type: 'object',
          properties: {
            error: {
              type: 'object',
              properties: {
                code: { type: 'string', examples: ['VALIDATION_ERROR', 'UNAUTHENTICATED', 'FORBIDDEN', 'NOT_FOUND', 'PREMIUM_REQUIRED', 'CONSENT_REQUIRED'] },
                message: { type: 'string' },
                details: {},
                requestId: { type: 'string' },
              },
            },
          },
        },
      },
    },
    paths,
  };
}
